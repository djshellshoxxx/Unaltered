export function archiveText(key: Key, vars?: Record<string, string | number>): string {
  const value: string = (getLang() === 'es' ? es : en)[key];
  return vars ? value.replace(/\{([A-Za-z]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match) : value;
}
