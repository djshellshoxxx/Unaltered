// The HTML template is repository input, but SR-3 requires builds to reject manually added executable tags instead of
// trusting a src-like substring inside another attribute. All script/style/link tags must come from the pinned builder.
import { spawnSync } from 'node:child_process';
import { appendFileSync, cpSync, existsSync, mkdtempSync, rmSync, symlinkSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';

const repo = fileURLToPath(new URL('../..', import.meta.url));

it.each([
  ['inline script with src text inside an attribute value', '<script data-note=" src=unused.js">globalThis.releaseProbe = true</script>'],
  ['external script without builder-generated SRI', '<SCRIPT src="./unexpected.js"></SCRIPT>'],
  ['style with a slash after its tag name', '<style/>body{color:red}</style>'],
  ['additional same-origin stylesheet without SRI', '<link rel="stylesheet" href="./styles.css">'],
  ['stylesheet with mixed-case attributes and whitespace', '<LiNk\tReL = " \tSTYLESHEET\n " HREF="./styles.css">'],
  ['alternate stylesheet with slash after the tag name', '<link/rel="alternate stylesheet" href="./styles.css">'],
])('build refuses a template containing %s', (_label, markup) => {
  const dir = mkdtempSync(join(tmpdir(), 'unaltered-template-gate-'));
  const deps = join(dir, 'node_modules');
  try {
    for (const path of ['src', 'scripts', 'package.json', 'LICENSE', 'tsconfig.json']) {
      cpSync(join(repo, path), join(dir, path), { recursive: true });
    }
    symlinkSync(join(repo, 'node_modules'), deps, 'junction');
    appendFileSync(join(dir, 'src', 'index.html'), '\n' + markup + '\n');
    const result = spawnSync(process.execPath, ['scripts/build.mjs'], { cwd: dir, encoding: 'utf8' });
    expect(result.status, result.stdout + result.stderr).not.toBe(0);
    expect(result.stderr).toContain('script/style/link tags in the template must be generated by the build');
    expect(existsSync(join(dir, 'dist', 'SHA256SUMS'))).toBe(false);
  } finally {
    // Remove the shared dependency link before recursive cleanup, including when build assertions fail.
    if (existsSync(deps)) unlinkSync(deps);
    rmSync(dir, { recursive: true, force: true });
  }
});
